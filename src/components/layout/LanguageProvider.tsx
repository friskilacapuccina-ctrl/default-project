export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("id");

  useEffect(() => {
    const stored = window.localStorage.getItem("biolearn-language");
    const initial: AppLanguage = stored === "en" ? "en" : "id";
    setLanguageState(initial);
    document.documentElement.lang = initial;
    document.title = translateText("BioLearn AI - Pembelajaran Biologi SMA", initial);
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
    document.title = translateText("BioLearn AI - Pembelajaran Biologi SMA", language);
  }, [language]);

  useEffect(() => {
    const attributes = ["title", "placeholder", "aria-label", "aria-description", "alt"];

    const localize = (root: Node) => {
      const textNodes: Text[] = [];
      if (root instanceof Text) textNodes.push(root);
      else {
        const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
        let textNode: Text | null;
        while ((textNode = walker.nextNode() as Text | null)) textNodes.push(textNode);
      }
      for (const textNode of textNodes) {
        const current = textNode.nodeValue ?? "";
        const saved = localizedTextValues.get(textNode);
        const source = saved && current === saved.translated ? saved.source : current;
        if (language === "id") {
          if (saved && current === saved.translated) textNode.nodeValue = saved.source;
          localizedTextValues.delete(textNode);
          continue;
        }
        const translated = translateText(source, language);
        if (translated !== source) {
          localizedTextValues.set(textNode, { source, translated });
          if (current !== translated) textNode.nodeValue = translated;
        } else if (saved && current === saved.translated) {
          textNode.nodeValue = source;
          localizedTextValues.delete(textNode);
        }
      }

      const elements: Element[] = [];
      if (root instanceof Element) elements.push(root);
      if (root instanceof Document) elements.push(root.documentElement);
      if ("querySelectorAll" in root) elements.push(...Array.from((root as ParentNode).querySelectorAll("*")));
      for (const element of elements) {
        for (const attribute of attributes) {
          const current = element.getAttribute(attribute);
          if (current === null) continue;
          let values = localizedAttributeValues.get(element);
          const saved = values?.get(attribute);
          const source = saved && current === saved.translated ? saved.source : current;
          if (language === "id") {
            if (saved && current === saved.translated) element.setAttribute(attribute, saved.source);
            values?.delete(attribute);
            continue;
          }
          const translated = translateText(source, language);
          if (translated !== source) {
            if (!values) {
              values = new Map();
              localizedAttributeValues.set(element, values);
            }
            values.set(attribute, { source, translated });
            if (current !== translated) element.setAttribute(attribute, translated);
          }
        }
      }
    };

    localize(document.body);
    const observer = new MutationObserver((records) => {
      for (const record of records) {
        if (record.type === "characterData" && record.target instanceof Text) {
          localize(record.target.parentNode ?? document.body);
        } else {
          record.addedNodes.forEach((node) => localize(node));
          if (record.type === "attributes" && record.target instanceof Element) localize(record.target);
        }
      }
    });
    observer.observe(document.body, {
      subtree: true,
      childList: true,
      characterData: true,
      attributes: true,
      attributeFilter: attributes,
    });
    return () => observer.disconnect();
  }, [language]);

  const setLanguage = (next: AppLanguage) => {
    window.localStorage.setItem("biolearn-language", next);
    document.documentElement.lang = next;
    setLanguageState(next);
  };

  const value = useMemo(() => ({ language, setLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}
