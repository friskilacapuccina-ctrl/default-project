export function translateText(text: string, language: AppLanguage) {
  if (language === "id") return text;
  const leading = text.match(/^\s*/)?.[0] ?? "";
  const trailing = text.match(/\s*$/)?.[0] ?? "";
  const trimmed = text.trim();
  if (!trimmed) return text;
  const exact = englishLabels[trimmed];
  if (exact) return `${leading}${exact}${trailing}`;

  // Translate known labels and phrases inside dynamic text such as counts and names.
  let translated = trimmed;
  for (const { pattern, target } of englishPhrases) {
    translated = translated.replace(pattern, (_match, prefix: string) => `${prefix}${target}`);
  }
  return `${leading}${translated}${trailing}`;
}

export function translate(text: string, language: AppLanguage) {
  return translateText(text, language);
}

